import openai

def generate_ai_analysis_response(prompt: str, lp_results: dict, ga_results: dict, api_key: str = None) -> str:
    """
    تولید پاسخ هوشمند بر اساس تحلیل واقعی خروجی‌های LP و GA
    """
    prompt_clean = prompt.strip().lower()
    
    # ۱. اتصال به مدل‌های واقعی OpenAI در صورت وارد کردن کلید API
    if api_key and api_key.strip():
        try:
            client = openai.OpenAI(api_key=api_key)
            context = f"""
            شما تحلیل‌گر ارشد سیستم تصمیم‌یار آشپزخانه ابری هستید.
            اطلاعات سیستم:
            - سود LP: {lp_results.get('total_profit', 0)}
            - برنامه تولید LP: {lp_results.get('production_plan', {})}
            - باقی‌مانده انبار: {lp_results.get('leftover_ingredients', {})}
            - هزینه GA: {ga_results.get('min_total_cost', 'N/A')}
            
            سوال کاربر: {prompt}
            پاسخ دقیق، کوتاه و بدون حاشیه بدهید.
            """
            response = client.chat.completions.create(
                model="gpt-3.5-turbo",
                messages=[{"role": "system", "content": context}],
                temperature=0.5
            )
            return response.choices[0].message.content
        except Exception:
            pass # در صورت بروز خطا در API، به موتور تحلیلی آفلاین منتقل می‌شود

    # ۲. موتور تحلیلی هوشمند تفکیک‌شده (حالت آفلاین)
    
    # بررسی اینکه آیا مدل‌ها اجرا شده‌اند یا خیر
    lp_run = bool(lp_results)
    ga_run = bool(ga_results)

    # ----------------------------------------------------
    # الف) سوالات مربوط به ناوگان توزیع، پیک، ارسال و زمان
    # ----------------------------------------------------
    if any(word in prompt_clean for word in ["پیک", "موتور", "ارسال", "مسیریابی", "زمان", "تاخیر"]):
        if not ga_run:
            return "🛵 **تحلیل ناوگان:** الگوریتم ژنتیک (GA) هنوز اجرا نشده است. لطفاً ابتدا از تب دوم، بهینه‌سازی مسیریابی را انجام دهید."
            
        best_routes = ga_results.get('best_routes', [])
        num_vehicles = len(best_routes) if best_routes else 0
        cost = ga_results.get('min_total_cost', 0)
        
        return f"""
🛵 **تحلیل ناوگان توزیع و زمان‌بندی (GA):**

* **تعداد پیک‌های تخصیص‌یافته:** {num_vehicles} پیک فعال.
* **علت تخصیص:** الگوریتم ژنتیک مسیرها را به‌گونه‌ای تقسیم کرده است که تمام سفارش‌ها در کمتر از **۳۵ دقیقه** تحویل داده شوند تا غذا سرد نشود و افت کیفیت پیدا نکند.
* **شاخص هزینه و جریمه کل:** {cost:.2f}

💡 **نتیجه‌گیری:** کاهش تعداد پیک‌ها باعث تاخیر شدید در تحویل و افزایش تصاعدی جریمه‌ها خواهد شد. این تعداد بهترین حالت برای حفظ گرمای غذاست.
        """

    # ----------------------------------------------------
    # ب) سوالات مربوط به ضایعات، انبار، مواد اولیه (برنج، گوشت و...)
    # ----------------------------------------------------
    elif any(word in prompt_clean for word in ["ضایعات", "انبار", "مواد", "برنج", "گوشت", "روغن", "موجودی"]):
        if not lp_run:
            return "📦 **تحلیل انبار:** الگوریتم برنامه‌ریزی خطی (LP) هنوز اجرا نشده است."
            
        leftovers = lp_results.get('leftover_ingredients', {})
        total_profit = lp_results.get('total_profit', 0)
        
        return f"""
📦 **تحلیل ضایعات و وضعیت انبار (LP):**

* **مواد باقی‌مانده در انبار (ضایعات متغیر):** 
{chr(10).join([f"  - {k}: {v} کیلوگرم" for k, v in leftovers.items()])}
* **سود خالص کل محاسبه‌شده:** {total_profit:,} هزار تومان

💡 **توصیه مدیریتی:** برای به صفر رساندن این ضایعات، پیشنهاد می‌شود ظرفیت زمان پخت آشپزخانه را افزایش دهید تا سیستم بتواند از این مواد باقی‌مانده نیز برای تولید غذای جدید استفاده کند.
        """

    # ----------------------------------------------------
    # ج) سوالات مربوط به گلوگاه تولید، علت محدودیت و نام غذاها
    # ----------------------------------------------------
    elif any(word in prompt_clean for word in ["جوجه", "کباب", "زرشک", "تولید", "چرا", "گلوگاه", "محدودیت", "علت"]):
        if not lp_run:
            return "🍳 **تحلیل تولید:** الگوریتم برنامه‌ریزی خطی (LP) هنوز اجرا نشده است."
            
        plan = lp_results.get('production_plan', {})
        leftovers = lp_results.get('leftover_ingredients', {})
        
        # تشخیص هوشمند گلوگاه (کدام ماده زودتر از همه در حال اتمام است)
        bottleneck = "ظرفیت زمان پخت آشپزخانه (Time Capacity)"
        if leftovers:
            min_ing = min(leftovers, key=leftovers.get)
            if leftovers[min_ing] <= 1.0: # اگر ماده‌ای کمتر از ۱ کیلو مانده باشد
                bottleneck = f"اتمام موجودی ماده اولیه **{min_ing}** در انبار"
            else:
                bottleneck = f"محدودیت در زمان پخت و نسبت سود به زمان"

        return f"""
🍳 **تحلیل خط تولید و محدودیت‌ها (LP):**

* **علت محدودیت تولید:** مدل ریاضی LP، میزان تولید را بر اساس محدودیت منابع متوقف می‌کند تا بالاترین سود ممکن را به دست آورد.
* **گلوگاه اصلی سیستم (Bottleneck):** عامل اصلی توقف تولید بیشتر، {bottleneck} است.
* **برنامه انتخاب‌شده:** {plan}

💡 **نتیجه‌گیری:** برای افزایش تولید غذاهای پرتقاضا (مثل جوجه‌کباب یا چلوکباب)، باید دقیقاً روی رفع این گلوگاه متمرکز شوید (مثلاً شارژ انبار یا افزایش ساعت کاری).
        """

    # ----------------------------------------------------
    # د) پاسخ عمومی برای سوالات نامفهوم یا خارج از چارچوب
    # ----------------------------------------------------
    else:
        return """
🤖 **دستیار تحلیلی آماده پاسخگویی است:**
من در حال حاضر به نتایج زنده مدل‌های شما متصل هستم. لطفاً سوال خود را صریح‌تر بپرسید. چند مثال:
* «گلوگاه تولید چیست؟»
* «چرا سه تا پیک داریم؟»
* «وضعیت ضایعات انبار چگونه است؟»
        """